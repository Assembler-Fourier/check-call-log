"""Real-use cases for the version 6 window, clicked and typed through the event loop (hidden, scratch folders)."""
import os
import sys

from drive6 import Rig

total = []


def case(title):
    print("\n=== " + title)


# -- 1. Live shift: the shift log ---------------------------------------------------------------------------------
case("1. Live shift: open straight on it, add a shift log line and type it")
rig = Rig("d1", now="2026-10-05 20:06")
rig.check("the logs of the shift are on show at once, and no file has been written", rig.show("Henry Marlow", "2026-10-05") and not os.path.exists(rig.out))
rig.check("the top line says whose shift and when", rig.app.who_label.cget("text") == "Henry Marlow" and "16:30 to 06:00" in rig.app.when_label.cget("text"), rig.app.when_label.cget("text"))
rig.app.flush()
quiet = rig.pdf_text(rig.files()["shift"])
rig.check("a shift log with nothing typed says NO MAJOR OCCURRENCE, and NTR for the handover", "NO MAJOR OCCURRENCE" in quiet and "NTR" in quiet, quiet[-120:])
rig.tab("shift")
rig.press("add_line")
rig.check("a new line opens at its place cell, the time already filled in", rig.box() is not None and rig.box()[2] == "area" and rig.entries()[0][0] == "20:06", rig.entries())
rig.type("Block B", "<Tab>")
rig.check("Tab moves on to what happened", rig.box() is not None and rig.box()[2] == "text")
rig.type("Exit door alarm sounding - reset, door secured", "<Return>")
rig.check("Enter in the last cell finishes the line", rig.box() is None and rig.entries() == [("20:06", "Block B", "Exit door alarm sounding - reset, door secured")], rig.entries())
text = rig.pdf_text(rig.files()["shift"])
rig.check("it is on the printed shift log; NO MAJOR OCCURRENCE has gone and the handover says AS PER OCCURRENCES ABOVE, not NTR",
          "Exit door alarm sounding" in text and "NO MAJOR OCCURRENCE" not in text and "NTR" not in text and "AS PER OCCURRENCES ABOVE" in text, text[-160:])
steps = len(rig.app.undone)
rig.press("add_line")
rig.type(None, "<Escape>")
rig.check("a new line left empty is taken away again, and is not something to undo", len(rig.entries()) == 1 and len(rig.app.undone) == steps, (rig.entries(), len(rig.app.undone), steps))
total += rig.close()

# -- 2. Live shift: patrols ---------------------------------------------------------------------------------------
case("2. Live shift, early: patrols")
rig = Rig("k9", now="2026-10-05 20:06")
rig.show("Henry Marlow", "2026-10-05")
rig.tab("patrols")
rig.check("the three usual rounds are on the log from the start, marked as still to come", len(rig.patrols()) == 3 and all(r["ahead"] for r in rig.app.pack["patrols"]["rows"]), rig.patrols())
rig.press("add_patrol")
rig.check("Add a patrol puts down the quarter of an hour just gone and opens its start", rig.patrols()[0] == ("19:51", "20:06", "All", "") and len(rig.patrols()) == 4 and rig.box() and rig.box()[2] == "start", rig.patrols())
rig.type("1930", "<Return>")
rig.check("a start typed loosely (1930) is read, and the finish goes with it", rig.patrols()[0] == ("19:30", "19:45", "All", "") and rig.box() and rig.box()[2] == "finish", rig.patrols())
rig.click_away()
rig.click("patrols", 0, "start")
rig.type("23:30", "<Return>")
rig.click_away()
rig.check("a time still to come is accepted and remarked on", ("23:30", "23:45", "All", "") in rig.patrols() and "ahead of the clock" in rig.said(), rig.said())
rig.press("undo")
rig.check("Undo takes that back", rig.patrols()[0] == ("19:30", "19:45", "All", "") and len(rig.patrols()) == 4, rig.patrols())
rig.at("2026-10-06 07:00")
rig.check("next morning the added patrol and the three usual rounds are all there", len(rig.patrols()) == 4 and rig.patrols()[0][0] == "19:30", rig.patrols())
total += rig.close()

# -- 3. Finished shift: patrols changed, re-sorted, removed, cleared, put back -------------------------------------
case("3. Finished shift: patrols")
rig = Rig("d3", now="2026-10-07 10:00")
rig.show("Lena Drayton", "2026-10-03")
rig.tab("patrols")
usual = rig.patrols()
rig.check("three usual rounds to start with", len(usual) == 3, usual)
for _ in (1, 2):
    rig.press("add_patrol")
    rig.type(None, "<Escape>")
spans = [(r["start"], r["finish"]) for r in rig.app.pack["patrols"]["rows"]]
rig.check("two more patrols can be added, none on top of another", len(spans) == 5 and all(a[1] <= b[0] for a, b in zip(spans, spans[1:])), rig.patrols())
rig.click("patrols", rig.patrols().index(usual[0]), "start")
rig.type("03:10", "<Tab>")
moved = next((p for p in rig.patrols() if p[0] == "03:10"), None)
box = rig.box()
rig.check("a start moved later re-sorts the list and the box follows the same patrol to its finish", moved and box and box[2] == "finish" and box[0].get() == moved[1], (moved, box and box[2]))
rig.type("03:40", "<Tab>")
rig.type("Gate left open - closed", "<Return>")
rig.click("patrols", [p[0] for p in rig.patrols()].index("03:10"), "area")
rig.type("Car park", "<Return>")
rig.click_away()
rig.check("finish, area and note all landed on that patrol", ("03:10", "03:40", "Car park", "Gate left open - closed") in rig.patrols(), rig.patrols())
rig.check("the other rounds are untouched", all(u in rig.patrols() for u in usual[1:]), rig.patrols())
at = [p[0] for p in rig.patrols()].index("03:10")
rig.click("patrols", at, "finish")
rig.type("02:50", "<Return>")
box = rig.box()
rig.check("a finish before the start is refused: the cell stays open with what was typed and says why under it",
          box is not None and box[0].get() == "02:50" and rig.grid("patrols").tip and "before it starts" in rig.grid("patrols").tip[2], rig.grid("patrols").tip)
rig.press("add_patrol")
rig.check("...and another button waits until it is put right", len(rig.patrols()) == 5 and rig.box() is not None)
rig.type("03:40", "<Return>")
rig.click_away()
rig.click("patrols", len(rig.patrols()) - 1, "notes")
rig.press("remove_patrol")
rig.check("Remove takes out the patrol being worked on", len(rig.patrols()) == 4, rig.patrols())
text = rig.pdf_text(rig.files()["patrols"])
rig.check("the printed patrol log shows the changed patrol", "03:10" in text and "Car park" in text and "Gate left open" in text)
kept = rig.patrols()
rig.press("clear_patrols")
rig.check("Clear all empties the list at once, with no question asked", rig.patrols() == [], rig.patrols())
rig.press("undo")
rig.check("...and Undo brings every patrol back", rig.patrols() == kept, rig.patrols())
rig.press("usual")
rig.check("Usual rounds puts the three suggestions back", rig.patrols() == usual, rig.patrols())
rig.press("undo")
rig.press("redo")
rig.check("Undo then Redo ends in the same place", rig.patrols() == usual, rig.patrols())
total += rig.close()

# -- 4. Finished shift: the shift log ------------------------------------------------------------------------------
case("4. Finished shift: several shift log lines, handover notes, re-ordering")
rig = Rig("d4", now="2026-10-07 10:00")
rig.show("Lena Drayton", "2026-10-03")
rig.tab("shift")
for when, place, what in (("23:15", "Main gate", "Delivery driver turned away - no booking"), ("19:40", "Block A", "Fire door propped open - closed"),
                          ("0205", "Car park", "Barrier arm stuck up - reported to maintenance")):
    rig.press("add_line")
    rig.type(when, "<Return>")
    rig.type(place, "<Return>")
    rig.type(what, "<Return>")
rig.check("three lines, kept in the order they happened", [e[0] for e in rig.entries()] == ["19:40", "23:15", "02:05"], rig.entries())
rig.click("shift", 0, "time")
rig.type("03:30", "<Tab>")
box = rig.box()
rig.check("after a time change re-sorts the lines the box is still on the same line", box is not None and box[2] == "area" and box[0].get() == "Block A", box and (box[2], box[0].get()))
rig.type("Block A rear", "<Return>")
rig.click_away()
rig.check("the moved line kept its text", ("03:30", "Block A rear", "Fire door propped open - closed") in rig.entries(), rig.entries())
rig.app.handover.insert("1.0", "Barrier at car park faulty.\nKeys 14 and 15 with maintenance.")
rig.key(rig.app.handover, "<KeyRelease>")
rig.pump(1100)
rig.click("shift", 1, "time")
rig.type("12:00", "<Return>")
rig.check("a time outside the shift is refused where it was typed", rig.box() is not None and "outside this shift" in (rig.grid("shift").tip or ("", "", ""))[2], rig.grid("shift").tip)
rig.type(None, "<Escape>")
rig.click("shift", 1, "time")
rig.type("06:10", "<Return>")
rig.click_away()
rig.check("a line just after the shift ended (06:10) is accepted and goes last", rig.entries()[-1][:2] == ("06:10", "Car park"), rig.entries())
log = rig.app.pack["shift"]
text = rig.pdf_text(rig.files()["shift"])
rig.check("handover notes are kept and everything is on the printed shift log", log["handover"].endswith("with maintenance.") and all(
    t in text for t in ("Barrier at car park faulty.", "Block A rear", "03:30", "06:10")))
rig.click("shift", 0, "area")
rig.press("remove_line")
rig.check("Remove takes out the line being typed in", len(rig.entries()) == 2 and all(e[0] != "23:15" for e in rig.entries()), rig.entries())
total += rig.close()

# -- 5. Check calls: typing down the list, keys, undo ---------------------------------------------------------------
case("5. Check calls: correcting times and responses")
rig = Rig("d5", now="2026-10-07 10:00")
rig.show("Lena Drayton", "2026-10-03")
names = [c["name"] for c in rig.calls()]
rig.click("calls", 0, "time")
rig.type("18:03", "<Return>")
box = rig.box()
rig.check("Enter after a time that re-sorts the list goes to the call that was next", box is not None and rig.app.call_for(box[1])["name"] == names[1], box and rig.app.call_for(box[1])["name"])
rig.type(None, "<Escape>")
grid = rig.grid("calls")
rig.check("after Esc the current cell stays where it was", grid.cursor is not None and rig.app.call_for(grid.cursor[0])["name"] == names[1])
below = rig.calls()[[c["name"] for c in rig.calls()].index(names[1]) + 1]["name"]      # (the list is in its new order now)
rig.key(grid.body, "<Down>")
rig.key(grid.body, "<Right>")
rig.check("the arrow keys move the current cell", grid.cursor[1] == "resp" and rig.app.call_for(grid.cursor[0])["name"] == below, grid.cursor)
rig.key(grid.body, "<Return>")
rig.type("No answer - rang back", "<Return>")
rig.click_away()
rig.check("Enter opens the current cell; the response is saved and marked as typed by hand",
          rig.app.call_for(grid.cursor[0]) is not None and any(c["name"] == below and c["response"] == "No answer - rang back" for c in rig.calls()))
rig.check("the printed log and the spreadsheet were written", "No answer - rang back" in rig.pdf_text(rig.files()["calls"]) and os.path.exists(os.path.join(rig.out, os.listdir(rig.out)[0])))
rig.press("undo")
rig.press("undo")
rig.check("two Undos put both changes back", not any(c["edited"] for c in rig.calls()), [c["name"] for c in rig.calls() if c["edited"]])
rig.click("calls", 3, "time")
rig.type("25:10", "<Return>")
rig.check("what cannot be a time is refused under the cell", rig.box() is not None and "is not a time" in (grid.tip or ("", "", ""))[2], grid.tip)
rig.type(None, "<Escape>")
total += rig.close()

# -- 6. Filling in the rest of the shift ----------------------------------------------------------------------------
case("6. Live shift: fill in the rest of the shift, change one, blank it again")
rig = Rig("d6", now="2026-10-10 20:10")
rig.show("Lena Drayton", "2026-10-10")
blank = sum(1 for c in rig.calls() if not c["call_text"])
rig.check("at 20:10 some calls are still to come and are blank; the next one is marked", 0 < blank < len(rig.calls()) and any(r.get("bar") for r in rig.grid("calls").rows), blank)
rig.check("the table has a 'now' rule between what is made and what is to come", any("rule" in r for r in rig.grid("calls").rows))
rig.press("fill")
rig.check("Fill in the rest: every call has a time and Ok, the ones ahead are known as such", all(c["call_text"] and c["response"] == "Ok" for c in rig.calls())
          and sum(1 for c in rig.calls() if c["ahead"]) == blank, rig.said())
rig.check("the rounds of the night are listed too, and the files are complete", len(rig.patrols()) == 3 and rig.calls()[-1]["call_text"] in rig.pdf_text(rig.files()["calls"]))
rig.check("the button now offers to blank them again", rig.app.buttons["fill"].text == "Leave the rest of the shift blank")
rig.press("fill")
rig.check("pressed again: only the calls that have happened are filled in (the rounds stay on the log)", sum(1 for c in rig.calls() if not c["call_text"]) == blank and len(rig.patrols()) == 3)
rig.press("undo")
rig.check("Undo brings the filled-in state back", all(c["call_text"] for c in rig.calls()))
rig.at("2026-10-11 07:00")
# A scheduled minute tick may have enabled the normal morning desk handover. Inspect the completed outgoing
# shift explicitly; the incoming controller's new shift correctly still has an enabled Fill button.
rig.show("Lena Drayton", "2026-10-10")
rig.check("the morning after nothing is 'ahead' and the button has nothing left to do",
          not any(c["ahead"] for c in rig.calls()) and not rig.app.buttons["fill"].enabled,
          (rig.app.shown_who(), rig.app.pack["date"], sum(bool(c["ahead"]) for c in rig.calls()), rig.app.buttons["fill"].enabled))
total += rig.close()

# -- 7. Several days, the chooser, the looks ---------------------------------------------------------------------
case("7. Several days at once, the chooser and the dark look")
rig = Rig("d7", now="2026-10-07 10:00")
rig.show("Lena Drayton", "2026-10-02", "2026-10-03")
chips = rig.app.day_box.winfo_children()
rig.check("two days chosen: a chip for each, the first on show", len(chips) == 2 and rig.app.day == 0 and rig.app.pack["date"].day == 2)
rig.tab("patrols")
rig.press(rig.app.day_box.winfo_children()[1])
rig.check("the second day's chip shows that day", rig.app.day == 1 and rig.app.pack["date"].day == 3)
rig.press("add_patrol")
rig.type(None, "<Escape>")
rig.check("a patrol added now goes on the day on show, not the other", len(rig.patrols(1)) == 4 and len(rig.patrols(0)) == 3, (rig.patrols(0), rig.patrols(1)))
rig.press("print")
rig.check("Open all to print writes both days' files", all(rig.files(d).get("all") and os.path.exists(rig.files(d)["all"]) for d in (0, 1)))
rig.check("both side panels are out to begin with, and their buttons are lit", rig.app.choosing and rig.app.chooser.winfo_ismapped() and rig.app.side.winfo_ismapped()
          and rig.app.buttons["change"].lit and rig.app.buttons["preview"].lit)
rig.check("with both out the row numbers and the times are still whole", all(v[0] and len(v[3]) >= 4 for v in rig.rows("patrols")) and rig.grid("calls").spans["no"][1] - rig.grid("calls").spans["no"][0] >= rig.app.px(44))
rig.press("preview")
rig.check("the page's button hides the page and is no longer lit; the chooser stays", not rig.app.side.winfo_ismapped() and not rig.app.buttons["preview"].lit and rig.app.chooser.winfo_ismapped())
rig.press("preview")
rig.check("...and shows it again", rig.app.side.winfo_ismapped() and rig.app.buttons["preview"].lit)
rig.press("change")
rig.check("the chooser's button puts the chooser away; the page stays", not rig.app.chooser.winfo_ismapped() and rig.app.side.winfo_ismapped() and not rig.app.buttons["change"].lit)
rig.press("change")
rig.root.geometry("1000x700+-2600+40")
rig.pump(400)
rig.check("only in a really narrow window does the page give way to the chooser", not rig.app.side.winfo_ismapped() and rig.app.previewing and rig.app.chooser.winfo_ismapped())
rig.press("preview")
rig.check("...and even then its button brings it out", rig.app.side.winfo_ismapped())
rig.root.geometry("1240x960+-2600+40")
rig.pump(400)
before = (rig.patrols(0), rig.patrols(1), rig.app.tab, rig.app.day)
rig.press("theme")
rig.check("the dark look keeps the days, the tab, the chooser and everything typed", rig.app.skin.theme == "dark" and (rig.patrols(0), rig.patrols(1), rig.app.tab, rig.app.day) == before and rig.app.choosing)
rig.press(rig.app.pills["Henry Marlow"])
rig.check("choosing another controller shows their shift at once", rig.app.who_label.cget("text") in ("Henry Marlow", "Lena Drayton") and rig.app.name == "Henry Marlow")
rig.press("done")
rig.check("Done puts the chooser away", not rig.app.choosing and not rig.app.chooser.winfo_ismapped())
rig.check("no error came up in any callback, in any case", not rig.errors, rig.errors[:1])
total += rig.close()

print("\n%d of %d checks passed" % (sum(total), len(total)))
sys.exit(0 if all(total) else 1)
